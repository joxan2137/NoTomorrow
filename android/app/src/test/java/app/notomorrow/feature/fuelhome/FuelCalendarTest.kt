    // MARK: - Day keys

    @Test
    fun `day key vectors`() {
        val rows = section("dayKey")
        assertEquals(16, rows.size)
        for (v in rows) {
            val stored = millis(v.getValue("storedUtc"))
            val zone = ZoneId.of(v.getValue("zone").jsonPrimitive.content)
            assertEquals(date(v.getValue("expected")), FuelCalendar.dayKey(stored, zone), "${v.getValue("storedUtc")} in $zone")
            // The plain floor the key replaces — the one that moves a Warsaw meal a day back in London.
            assertEquals(date(v.getValue("plainStartOfDay")), Days.date(stored, zone), "plain ${v.getValue("storedUtc")} in $zone")
        }
    }

    /** A day logged at Warsaw midnight stays on its calendar day when read in London, New York or Tokyo. */
    @Test
    fun `day key survives a time-zone change`() {
        for (zoneId in listOf("Europe/London", "America/New_York", "Asia/Tokyo", "Europe/Warsaw")) {
            val abroad = ZoneId.of(zoneId)
            for (iso in listOf("2026-03-29", "2026-07-15", "2026-10-25", "2026-12-31")) {
                val day = LocalDate.parse(iso)
                val stored = Days.millis(day, warsaw)
                assertEquals(day, FuelCalendar.dayKey(stored, abroad), "$zoneId $iso")
                if (zoneId == "America/New_York") {
                    assertNotEquals(day, Days.date(stored, abroad), "plain floor moves it a day back")
                }
            }
        }
    }

    @Test
    fun `stored day bounds vectors`() {
        val rows = section("storedDayBounds")
        assertEquals(6, rows.size)
        for (v in rows) {
            val day = requireNotNull(date(v.getValue("day")))
            val zone = ZoneId.of(v.getValue("zone").jsonPrimitive.content)
            val bounds = FuelCalendar.storedDayBounds(day, zone)
            assertEquals(millis(v.getValue("lowerUtc")), bounds.lower, "$day lower")
            assertEquals(millis(v.getValue("upperUtc")), bounds.upper, "$day upper")
        }
    }

    /** `storedDayBounds` is exactly the set of stored values whose `dayKey` is that day, DST days included. */
    @Test
    fun `stored day bounds match the day key`() {
        val quarterHour = 15L * 60 * 1000
        for (iso in listOf("2026-03-28", "2026-03-29", "2026-03-30", "2026-10-24", "2026-10-25", "2026-10-26")) {
            val target = LocalDate.parse(iso)
            val bounds = FuelCalendar.storedDayBounds(target, warsaw)
            val midnight = Days.millis(target, warsaw)
            var probe = midnight - 36 * 3_600_000L
            while (probe < midnight + 48 * 3_600_000L) {
                val inBounds = probe >= bounds.lower && probe < bounds.upper
                assertEquals(inBounds, FuelCalendar.dayKey(probe, warsaw) == target, "$iso ${Instant.ofEpochMilli(probe)}")
                probe += quarterHour
            }
        }
    }

    // MARK: - Data

    @Test
    fun `kcal by day sums rows that share a day key`() {
        val today = LocalDate.of(2026, 9, 22)
        val midnight = Days.millis(today, warsaw)
        val rows = listOf(
            DayKcal(day = midnight, kcal = 500.0),
            // Logged an hour further east: the stored midnight is an hour early, still today's meal.
            DayKcal(day = midnight - 3_600_000L, kcal = 250.0),
            DayKcal(day = Days.millis(today.minusDays(1), warsaw), kcal = 700.0),
        )
        assertEquals(
            mapOf(today to 750.0, today.minusDays(1) to 700.0),
            FuelCalendar.kcalByDay(rows, warsaw),
        )
        assertEquals(emptyMap(), FuelCalendar.kcalByDay(emptyList(), warsaw))
    }

    @Test
    fun `the vector file is the contract`() {
        // Guards against a trimmed copy: every section the iOS suites read is present and non-empty.
        for (name in listOf("permille", "level", "layout", "firstVisibleColumn", "stats", "rolledDay", "resumedDay", "dayKey", "storedDayBounds")) {
            assertTrue((vectors[name] as? JsonArray)?.isNotEmpty() == true, name)
        }
    }
